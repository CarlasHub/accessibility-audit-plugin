import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { createReadStream } from 'node:fs';
import {
  copyFile,
  cp,
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rm,
  writeFile
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, join, resolve } from 'node:path';
import { promisify } from 'node:util';
import { createGunzip } from 'node:zlib';

const execFileAsync = promisify(execFile);
const root = resolve(import.meta.dirname, '..');
const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const version = packageJson.version;
const outputRoot = join(root, 'marketplace', 'carlashub-plugin-marketplace');
const payloadRoot = join(outputRoot, 'accessibility-audit');
const harnesses = ['claude', 'copilot-cli', 'copilot-vscode'];
const generatedNotice = 'Generated by npm run build:marketplace. Do not edit this payload directly.\n';
const marketplacePackager = `npm@${packageJson.marketplacePackagerVersion}`;
const npxExecutable = process.platform === 'win32' ? 'npx.cmd' : 'npx';
const runtimeImportExpression = "const e=process.env,r=e.CLAUDE_PLUGIN_ROOT||e.COPILOT_PLUGIN_ROOT||e.PLUGIN_ROOT||process.cwd();const n=process.platform==='win32'&&r[0]==='/'&&r[2]==='/'?r[1].toUpperCase()+':'+r.slice(2):r;e.PLUGIN_ROOT=n;import('node:url').then(u=>import(u.pathToFileURL(n+'/_runtime/bin/launch-mcp.mjs').href))";

if (!/^\d+\.\d+\.\d+$/.test(packageJson.marketplacePackagerVersion ?? '')) {
  throw new Error('package.json must define an exact marketplacePackagerVersion.');
}

function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

