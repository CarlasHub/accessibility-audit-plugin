function runtimeHookExpression(filename) {
  return `const e=process.env,r=e.CLAUDE_PLUGIN_ROOT||e.COPILOT_PLUGIN_ROOT||e.PLUGIN_ROOT||'';const n=process.platform==='win32'&&r[0]==='/'&&r[2]==='/'?r[1].toUpperCase()+':'+r.slice(2):r;import('node:url').then(u=>import(u.pathToFileURL(n+'/_runtime/hooks/${filename}').href))`;
}

async function sha256(filePath) {
  const hash = createHash('sha256');
  hash.update(await readFile(filePath));
  return hash.digest('hex');
}

function uncompressedTarSha256(filePath) {
  return new Promise((resolveHash, rejectHash) => {
    const hash = createHash('sha256');
    const archive = createReadStream(filePath);
    const gunzip = createGunzip();

    archive.once('error', rejectHash);
    gunzip.once('error', rejectHash);
    gunzip.on('data', (chunk) => hash.update(chunk));
    gunzip.once('end', () => resolveHash(hash.digest('hex')));
    archive.pipe(gunzip);
  });
}

async function selectStableTarball(generatedTarball, temporaryRoot) {
  const tarballName = basename(generatedTarball);
  const existingTarball = join(payloadRoot, 'claude', '_install-source', tarballName);
  const existingManifestPath = join(payloadRoot, 'claude', 'install-manifest.json');

  try {
    const existingManifest = JSON.parse(await readFile(existingManifestPath, 'utf8'));
    if (
      existingManifest.version !== version
      || existingManifest.packageName !== packageJson.name
      || existingManifest.tarball !== tarballName
    ) {
      return { path: generatedTarball, reused: false };
    }

    const [existingDigest, existingContentDigest, generatedContentDigest] = await Promise.all([
      sha256(existingTarball),
      uncompressedTarSha256(existingTarball),
      uncompressedTarSha256(generatedTarball)
    ]);
    if (
      existingManifest.sha256 !== existingDigest
      || existingContentDigest !== generatedContentDigest
    ) {
      return { path: generatedTarball, reused: false };
    }

    const stableTarball = join(temporaryRoot, `stable-${tarballName}`);
    await copyFile(existingTarball, stableTarball);
    return { path: stableTarball, reused: true };
  } catch {
    return { path: generatedTarball, reused: false };
  }
}

async function copySharedPayload(destination) {
  await cp(join(root, 'skills'), join(destination, 'skills'), { recursive: true });
  await cp(join(root, 'commands'), join(destination, 'commands'), { recursive: true });
  await cp(join(root, 'marketplace', 'runtime'), join(destination, '_runtime'), { recursive: true });
  await mkdir(join(destination, 'hooks'), { recursive: true });
  await copyFile(join(root, 'marketplace', 'runtime', 'hooks', 'launcher.cjs'), join(destination, 'hooks', 'launcher.cjs'));
  await copyFile(join(root, 'LICENSE'), join(destination, 'LICENSE'));
  await writeFile(join(destination, 'GENERATED.md'), generatedNotice, 'utf8');
  await writeFile(join(destination, '.mcp.json'), json(mcpConfig()), 'utf8');
}

const temporaryRoot = await mkdtemp(join(tmpdir(), 'accessibility-audit-pack-'));
try {
  // npm install and npm pack have both changed bundled-dependency filtering
  // between releases. Assemble the package in an isolated directory with one
  // explicit npm version so the archive does not depend on the contributor's
  // npm version or existing node_modules tree.
  const packageRoot = join(temporaryRoot, 'package-source');
  await mkdir(packageRoot, { recursive: true });
  await copyFile(join(root, 'package.json'), join(packageRoot, 'package.json'));
  await copyFile(join(root, 'package-lock.json'), join(packageRoot, 'package-lock.json'));
  for (const packageEntry of packageJson.files) {
    const relativePath = packageEntry.replace(/\/$/, '');
    await cp(join(root, relativePath), join(packageRoot, relativePath), { recursive: true });
  }
  await execFileAsync(npxExecutable, [
    '--yes',
    marketplacePackager,
    'ci',
    '--ignore-scripts',
    '--omit=dev',
    '--no-audit',
    '--no-fund'
  ], {
    cwd: packageRoot,
    maxBuffer: 16 * 1024 * 1024
  });

  const { stdout } = await execFileAsync(npxExecutable, [
    '--yes',
    marketplacePackager,
    'pack',
    '--json',
    '--pack-destination',
    temporaryRoot
  ], {
    cwd: packageRoot,
    maxBuffer: 4 * 1024 * 1024
  });
  const packResult = JSON.parse(stdout);
  const tarballName = packResult[0]?.filename;
  if (!tarballName) throw new Error('npm pack did not return a tarball filename.');
  const generatedTarball = join(temporaryRoot, basename(tarballName));
  const { path: tarballSource, reused } = await selectStableTarball(generatedTarball, temporaryRoot);
  const digest = await sha256(tarballSource);
  const installManifest = {
    version,
    packageName: packageJson.name,
    tarball: basename(tarballName),
    sha256: digest,
    entrypoint: 'dist/mcp.js',
    template: 'assets/accessibility-report-template.xlsx',
    overrides: packageJson.overrides ?? {}
  };

  await rm(payloadRoot, { recursive: true, force: true });
  for (const harness of harnesses) {
    const destination = join(payloadRoot, harness);
    await mkdir(join(destination, '_install-source'), { recursive: true });
    await copySharedPayload(destination);
    await copyFile(tarballSource, join(destination, '_install-source', basename(tarballName)));
    await writeFile(join(destination, 'install-manifest.json'), json(installManifest), 'utf8');
    await writeFile(join(destination, 'README.md'), payloadReadme(harness), 'utf8');
  }

  const claudeRoot = join(payloadRoot, 'claude');
  await mkdir(join(claudeRoot, '.claude-plugin'), { recursive: true });
  await mkdir(join(claudeRoot, 'hooks'), { recursive: true });
  await writeFile(join(claudeRoot, '.claude-plugin', 'plugin.json'), json({
    ...pluginManifest('accessibility-audit'),
    commands: './commands/',
    hooks: './hooks/hooks.json'
  }), 'utf8');
  await writeFile(join(claudeRoot, 'hooks', 'hooks.json'), json(claudeHooks()), 'utf8');

  const copilotCliRoot = join(payloadRoot, 'copilot-cli');
  await mkdir(join(copilotCliRoot, 'hooks'), { recursive: true });
  await writeFile(join(copilotCliRoot, 'plugin.json'), json({
    ...pluginManifest('accessibility-audit'),
    commands: './commands/',
    hooks: './hooks/hooks.json'
  }), 'utf8');
  await writeFile(join(copilotCliRoot, 'hooks', 'hooks.json'), json(copilotHooks()), 'utf8');

  const copilotVscodeRoot = join(payloadRoot, 'copilot-vscode');
  await mkdir(join(copilotVscodeRoot, '.claude-plugin'), { recursive: true });
  await writeFile(join(copilotVscodeRoot, '.claude-plugin', 'plugin.json'), json({
    ...pluginManifest('accessibility-audit-vscode'),
    hooks: './hooks/hooks.json'
  }), 'utf8');
  await writeFile(join(copilotVscodeRoot, 'hooks', 'hooks.json'), json(claudeHooks()), 'utf8');

  const catalogRoot = join(outputRoot, 'catalog-fragments');
  await rm(catalogRoot, { recursive: true, force: true });
  await mkdir(catalogRoot, { recursive: true });
  await writeFile(join(catalogRoot, 'claude.json'), json({
    name: 'accessibility-audit',
    description: 'Evidence-backed accessibility pre-audit for WCAG 2.2 A/AA with review-ready reports and evidence.',
    source: {
      source: 'git-subdir',
      url: 'https://github.com/CarlasHub/accessibility-audit-plugin.git',
      ref: 'main',
      path: 'marketplace/carlashub-plugin-marketplace/accessibility-audit/claude'
    }
  }), 'utf8');
  await writeFile(join(catalogRoot, 'copilot.json'), json([
    {
      name: 'accessibility-audit',
      description: 'Evidence-backed accessibility pre-audit for WCAG 2.2 A/AA in Copilot CLI.',
      version,
      source: 'accessibility-audit/copilot-cli'
    },
    {
      name: 'accessibility-audit-vscode',
      description: 'Evidence-backed accessibility pre-audit for WCAG 2.2 A/AA in Copilot for VS Code.',
      version,
      source: 'accessibility-audit/copilot-vscode'
    }
  ]), 'utf8');

  const generatedFiles = [];
  for (const harness of harnesses) {
    const files = await readdir(join(payloadRoot, harness));
    generatedFiles.push(`${harness}: ${files.sort().join(', ')}`);
  }
  await execFileAsync(process.execPath, [
    join(root, 'scripts', 'verify-site-neutrality.mjs'),
    '--require-dist',
    '--include-marketplace'
  ], { cwd: root });
  const archiveStatus = reused ? 'reused canonical archive bytes' : 'created new archive bytes';
  process.stdout.write(`Generated marketplace payload ${version} (${archiveStatus})\n${generatedFiles.join('\n')}\nSHA-256: ${digest}\n`);
} finally {
  await rm(temporaryRoot, { recursive: true, force: true });
}
