import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import {
  copyFile,
  cp,
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rm,
  writeFile
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, join, resolve } from 'node:path';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);
const root = resolve(import.meta.dirname, '..');
const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const version = packageJson.version;
const outputRoot = join(root, 'marketplace', 'rai-ops-plugin-marketplace');
const payloadRoot = join(outputRoot, 'accessibility-audit');
const harnesses = ['claude', 'copilot-cli', 'copilot-vscode'];
const generatedNotice = 'Generated by npm run build:marketplace. Do not edit this payload directly.\n';
const runtimeImportExpression = "const e=process.env,r=e.CLAUDE_PLUGIN_ROOT||e.COPILOT_PLUGIN_ROOT||e.PLUGIN_ROOT||process.cwd();const n=process.platform==='win32'&&r[0]==='/'&&r[2]==='/'?r[1].toUpperCase()+':'+r.slice(2):r;e.PLUGIN_ROOT=n;import('node:url').then(u=>import(u.pathToFileURL(n+'/_runtime/bin/launch-mcp.mjs').href))";

function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function pluginManifest(name) {
  return {
    name,
    version,
    description: 'Evidence-backed WCAG 2.2 A/AA page audits with headless desktop, mobile, reflow, keyboard, link, component evidence, and validated Excel reporting.',
    author: { name: 'Radancy' },
    homepage: 'https://github.com/carla-goncalves_radancy/accessibility-audit-plugin',
    repository: 'https://github.com/carla-goncalves_radancy/accessibility-audit-plugin',
    license: 'MIT',
    keywords: ['accessibility', 'wcag', 'axe', 'playwright', 'testing'],
    category: 'development',
    skills: './skills/',
    mcpServers: './.mcp.json'
  };
}

function mcpConfig() {
  return {
    mcpServers: {
      'accessibility-audit': {
        command: 'node',
        args: ['-e', runtimeImportExpression]
      }
    }
  };
}

function claudeHooks() {
  return {
    hooks: {
      SessionStart: [{
        hooks: [{
          type: 'command',
          command: `node -e "${runtimeHookExpression('bootstrap.mjs')}"`,
          timeout: 600
        }]
      }]
    }
  };
}

function copilotHooks() {
  return {
    version: 1,
    hooks: {
      sessionStart: [{
        type: 'command',
        command: 'node hooks/launcher.cjs bootstrap.mjs',
        timeoutSec: 600
      }]
    }
  };
}

function payloadReadme(harness) {
  const client = harness === 'claude'
    ? 'Claude Code and Claude Desktop'
    : harness === 'copilot-cli'
      ? 'GitHub Copilot CLI'
      : 'GitHub Copilot in VS Code';
  return `# Accessibility Audit for ${client}\n\nAccessibility Audit runs evidence-backed WCAG 2.2 A/AA checks against explicit authorized page URLs and writes a validated Excel report, JSON evidence, linked component screenshots, and a portable ZIP. The engine is site-independent: it contains no customer-specific hostnames, page assumptions, selectors, rules, or defaults. It does not crawl a site or certify conformance.\n\n## Use\n\nAsk ${client} to use the Accessibility Audit plugin with one URL, several URLs, or one XLSX/CSV/TXT/JSON page-list file. The plugin confirms the exact scope, landing-page QA URL, and auditor before starting. The editable auditor default is \`Automated\`.\n\nThe audit runs headlessly at desktop, mobile, and 320px reflow sizes. It reports progress and supports graceful cancellation with partial output. A full-site audit requires a complete canonical URL list. Screen-reader, physical-device, content-meaning, and other judgment-based procedures remain guided manual checks.\n\nIf consent or another modal surface cannot be dismissed, the plugin records an interaction-coverage blocker and does not claim that underlying page interactions ran. JSON preserves axe incomplete/pass metadata, keyboard and link truncation, and a page/viewport/test-area coverage matrix. Incomplete, sampled, blocked, manual, and unperformed checks are not passes.\n\n## Isolation and first activation\n\nNode.js 22 or later and npm must be available to the client. The first activation verifies the bundled runtime checksum and installs it into client-owned plugin data; it never modifies the project open in the editor. If no supported Chromium browser exists, the first confirmed audit installs Playwright Chromium once into the same private plugin storage unless automatic browser installation is disabled.\n\n## Output\n\nThe default output is \`Accessibility Audit Results\` under the user's home directory. Extract the generated ZIP and keep \`Accessibility_Audit_Report.xlsx\` beside the \`screenshots\` tree so the workbook's relative evidence links work. Treat \`confirmed\`, \`review\`, \`blocker\`, and \`manual\` evidence categories separately; an empty automated result is not proof of accessibility. Contextual screenshots may support confirmed, blocker, and review evidence when capture succeeds.\n\nThe workbook is generated from a byte-identical copy of \`Accessibility Testing Boilerplate v.4 (4)\`. The five worksheet names and order, worksheet tab colours, existing colour scheme, formulas, validations, and 32 Accessibility Report fields are preserved. \`Page Inventroy\` contains only a headerless column-A list of unique URLs whose browser testing started. \`Image Inventory\` contains only a headerless column-A list of unique linked relative screenshot references. No inventory metadata columns, tables, or additional worksheets are added.\n\nThis directory is generated from the private Accessibility Audit source repository. Do not edit it directly.\n`;
}

function runtimeHookExpression(filename) {
  return `const e=process.env,r=e.CLAUDE_PLUGIN_ROOT||e.COPILOT_PLUGIN_ROOT||e.PLUGIN_ROOT||'';const n=process.platform==='win32'&&r[0]==='/'&&r[2]==='/'?r[1].toUpperCase()+':'+r.slice(2):r;import('node:url').then(u=>import(u.pathToFileURL(n+'/_runtime/hooks/${filename}').href))`;
}

async function sha256(filePath) {
  const hash = createHash('sha256');
  hash.update(await readFile(filePath));
  return hash.digest('hex');
}

async function copySharedPayload(destination) {
  await cp(join(root, 'skills'), join(destination, 'skills'), { recursive: true });
  await cp(join(root, 'commands'), join(destination, 'commands'), { recursive: true });
  await cp(join(root, 'marketplace', 'runtime'), join(destination, '_runtime'), { recursive: true });
  await mkdir(join(destination, 'hooks'), { recursive: true });
  await copyFile(join(root, 'marketplace', 'runtime', 'hooks', 'launcher.cjs'), join(destination, 'hooks', 'launcher.cjs'));
  await copyFile(join(root, 'LICENSE'), join(destination, 'LICENSE'));
  await writeFile(join(destination, 'GENERATED.md'), generatedNotice, 'utf8');
  await writeFile(join(destination, '.mcp.json'), json(mcpConfig()), 'utf8');
}

const temporaryRoot = await mkdtemp(join(tmpdir(), 'accessibility-audit-pack-'));
try {
  const { stdout } = await execFileAsync('npm', ['pack', '--json', '--pack-destination', temporaryRoot], {
    cwd: root,
    maxBuffer: 4 * 1024 * 1024
  });
  const packResult = JSON.parse(stdout);
  const tarballName = packResult[0]?.filename;
  if (!tarballName) throw new Error('npm pack did not return a tarball filename.');
  const tarballSource = join(temporaryRoot, basename(tarballName));
  const digest = await sha256(tarballSource);
  const installManifest = {
    version,
    packageName: packageJson.name,
    tarball: basename(tarballSource),
    sha256: digest,
    entrypoint: 'dist/mcp.js',
    template: 'assets/accessibility-report-template.xlsx',
    overrides: packageJson.overrides ?? {}
  };

  await rm(payloadRoot, { recursive: true, force: true });
  for (const harness of harnesses) {
    const destination = join(payloadRoot, harness);
    await mkdir(join(destination, '_install-source'), { recursive: true });
    await copySharedPayload(destination);
    await copyFile(tarballSource, join(destination, '_install-source', basename(tarballSource)));
    await writeFile(join(destination, 'install-manifest.json'), json(installManifest), 'utf8');
    await writeFile(join(destination, 'README.md'), payloadReadme(harness), 'utf8');
  }

  const claudeRoot = join(payloadRoot, 'claude');
  await mkdir(join(claudeRoot, '.claude-plugin'), { recursive: true });
  await mkdir(join(claudeRoot, 'hooks'), { recursive: true });
  await writeFile(join(claudeRoot, '.claude-plugin', 'plugin.json'), json({
    ...pluginManifest('accessibility-audit'),
    commands: './commands/',
    hooks: './hooks/hooks.json'
  }), 'utf8');
  await writeFile(join(claudeRoot, 'hooks', 'hooks.json'), json(claudeHooks()), 'utf8');

  const copilotCliRoot = join(payloadRoot, 'copilot-cli');
  await mkdir(join(copilotCliRoot, 'hooks'), { recursive: true });
  await writeFile(join(copilotCliRoot, 'plugin.json'), json({
    ...pluginManifest('accessibility-audit'),
    commands: './commands/',
    hooks: './hooks/hooks.json'
  }), 'utf8');
  await writeFile(join(copilotCliRoot, 'hooks', 'hooks.json'), json(copilotHooks()), 'utf8');

  const copilotVscodeRoot = join(payloadRoot, 'copilot-vscode');
  await mkdir(join(copilotVscodeRoot, '.claude-plugin'), { recursive: true });
  await writeFile(join(copilotVscodeRoot, '.claude-plugin', 'plugin.json'), json({
    ...pluginManifest('accessibility-audit-vscode'),
    hooks: './hooks/hooks.json'
  }), 'utf8');
  await writeFile(join(copilotVscodeRoot, 'hooks', 'hooks.json'), json(claudeHooks()), 'utf8');

  const catalogRoot = join(outputRoot, 'catalog-fragments');
  await rm(catalogRoot, { recursive: true, force: true });
  await mkdir(catalogRoot, { recursive: true });
  await writeFile(join(catalogRoot, 'claude.json'), json({
    name: 'accessibility-audit',
    description: 'Evidence-backed WCAG 2.2 A/AA page audits with validated Excel reporting.',
    source: {
      source: 'git-subdir',
      url: 'https://github.com/radancy-pe/rai-ops-plugin-marketplace.git',
      ref: 'main',
      path: 'accessibility-audit/claude'
    }
  }), 'utf8');
  await writeFile(join(catalogRoot, 'copilot.json'), json([
    {
      name: 'accessibility-audit',
      description: 'Evidence-backed WCAG 2.2 A/AA page audits for Copilot CLI.',
      version,
      source: 'accessibility-audit/copilot-cli'
    },
    {
      name: 'accessibility-audit-vscode',
      description: 'Evidence-backed WCAG 2.2 A/AA page audits for Copilot in VS Code.',
      version,
      source: 'accessibility-audit/copilot-vscode'
    }
  ]), 'utf8');

  const generatedFiles = [];
  for (const harness of harnesses) {
    const files = await readdir(join(payloadRoot, harness));
    generatedFiles.push(`${harness}: ${files.sort().join(', ')}`);
  }
  await execFileAsync(process.execPath, [
    join(root, 'scripts', 'verify-site-neutrality.mjs'),
    '--require-dist',
    '--include-marketplace'
  ], { cwd: root });
  process.stdout.write(`Generated marketplace payload ${version}\n${generatedFiles.join('\n')}\nSHA-256: ${digest}\n`);
} finally {
  await rm(temporaryRoot, { recursive: true, force: true });
}
